// Builds the PixelMplus10 / PixelMplus12 web fonts, each in two tiers.
// "PixelMplusNN" holds only the characters in the site's own source, so a page usually needs one small file.
// "PixelMplusNN Extra" is the whole font split by Unicode block, used only for text the build could not see, such as pinned repository descriptions.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import * as fontkit from 'fontkit';
import subsetFont from 'subset-font';

const SIZES = [10, 12];
const SRC_DIR = new URL('../src/', import.meta.url);
const OUT_DIR = new URL('../public/fonts/pixelmplus/', import.meta.url);
const CSS_FILE = new URL('../src/styles/pixelmplus.css', import.meta.url);
const KANJI_CHUNK_SIZE = 1000;

async function collectSourceText(dir) {
	let text = '';
	for (const entry of await readdir(dir, { withFileTypes: true })) {
		const url = new URL(entry.name + (entry.isDirectory() ? '/' : ''), dir);
		if (entry.isDirectory()) text += await collectSourceText(url);
		else if (/\.(astro|ts|tsx|md)$/.test(entry.name)) text += await readFile(url, 'utf8');
	}
	return text;
}

const hex = (value) => value.toString(16).toUpperCase();

// Merges consecutive code points into ranges such as U+4E00-4E10 to keep unicode-range short.
function toUnicodeRange(points) {
	const ranges = [];
	let start = points[0];
	let previous = points[0];
	for (const cp of [...points.slice(1), Number.POSITIVE_INFINITY]) {
		if (cp === previous + 1) {
			previous = cp;
			continue;
		}
		ranges.push(start === previous ? `U+${hex(start)}` : `U+${hex(start)}-${hex(previous)}`);
		start = cp;
		previous = cp;
	}
	return ranges.join(',');
}

function fontFace(family, file, unicodeRange) {
	return `@font-face {\n\tfont-family: '${family}';\n\tfont-display: swap;\n\tsrc: url('/fonts/pixelmplus/${file}.woff2') format('woff2');\n\tunicode-range: ${unicodeRange};\n}`;
}

const ascii = Array.from({ length: 0x5f }, (_, index) => 0x20 + index);
const sourceCodePoints = new Set([...ascii, ...[...(await collectSourceText(SRC_DIR))].map((char) => char.codePointAt(0))]);

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

async function buildFamily(size) {
	const family = `PixelMplus${size}`;
	const source = await readFile(new URL(`../fonts/pixelmplus/PixelMplus${size}-Regular.ttf`, import.meta.url));
	const fontCodePoints = [...fontkit.create(source).characterSet].sort((a, b) => a - b);

	async function writeChunk(name, codePoints) {
		const woff2 = await subsetFont(source, String.fromCodePoint(...codePoints), { targetFormat: 'woff2' });
		await writeFile(new URL(`${size}-${name}.woff2`, OUT_DIR), woff2);
		return woff2.length;
	}

	const faces = [];
	const siteCodePoints = fontCodePoints.filter((cp) => sourceCodePoints.has(cp));
	const siteSize = await writeChunk('site', siteCodePoints);
	faces.push(fontFace(family, `${size}-site`, toUnicodeRange(siteCodePoints)));

	const isKanji = (cp) => cp >= 0x4e00 && cp <= 0x9fff;
	const extraChunks = [
		{ name: 'extra-latin', codePoints: fontCodePoints.filter((cp) => cp < 0x3000) },
		{ name: 'extra-kana', codePoints: fontCodePoints.filter((cp) => (cp >= 0x3000 && cp < 0x4e00) || cp >= 0xa000) },
	];
	const kanji = fontCodePoints.filter(isKanji);
	for (let index = 0; index * KANJI_CHUNK_SIZE < kanji.length; index += 1) {
		extraChunks.push({
			name: `extra-kanji-${index}`,
			codePoints: kanji.slice(index * KANJI_CHUNK_SIZE, (index + 1) * KANJI_CHUNK_SIZE),
		});
	}

	let extraSize = 0;
	for (const chunk of extraChunks) {
		extraSize += await writeChunk(chunk.name, chunk.codePoints);
		// A whole span is fine here: glyphs missing from the font simply fall through to the next family.
		const range = `U+${hex(chunk.codePoints[0])}-${hex(chunk.codePoints.at(-1))}`;
		faces.push(fontFace(`${family} Extra`, `${size}-${chunk.name}`, range));
	}

	console.log(
		`${family}: site ${siteCodePoints.length} glyphs, ${(siteSize / 1024).toFixed(1)} KiB / extra ${extraChunks.length} chunks, ${(extraSize / 1024).toFixed(0)} KiB`,
	);
	return faces;
}

const faces = [];
for (const size of SIZES) faces.push(...(await buildFamily(size)));

const header = '/* Generated by scripts/build-fonts.mjs from PixelMplus (M+ FONT LICENSE). Do not edit by hand. */\n';
await writeFile(CSS_FILE, `${header}${faces.join('\n\n')}\n`);
